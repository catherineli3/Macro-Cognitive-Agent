# Convenience accessors
# ══════════════════════════════════════════════════════════════════════

CASES: list[HistoricalCase] = []


def _ensure_loaded():
    global CASES
    if not CASES:
        CASES.clear()
        CASES.extend(_cases)


def get_case_by_id(case_id: str) -> Optional[HistoricalCase]:
    _ensure_loaded()
    for c in CASES:
        if c.case_id == case_id:
            return c
    return None


def get_cases_by_cycle(cycle: MacroCycle) -> list[HistoricalCase]:
    _ensure_loaded()
    return [c for c in CASES if c.cycle == cycle]


def get_cases_by_difficulty(difficulty: str) -> list[HistoricalCase]:
    _ensure_loaded()
    return [c for c in CASES if c.difficulty == difficulty]


def get_cases_by_tag(tag: str) -> list[HistoricalCase]:
    _ensure_loaded()
    tag_lower = tag.lower()
    return [c for c in CASES if tag_lower in c.title.lower() or tag_lower in c.cycle.value]


def case_count() -> int:
    _ensure_loaded()
    return len(CASES)
