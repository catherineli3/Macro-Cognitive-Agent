# Uses minimal tuple format: each case = (id, date, title, cycle, regime_dict,
#   conditions_dict, beliefs, narrative, [competing], flows, assets_dict,
#   expert_view, outcome, difficulty, lesson, is_tp, [causal_chain], [risks], [unknowns])
