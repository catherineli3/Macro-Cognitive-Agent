from __future__ import annotations
from dataclasses import dataclass, field
from enum import Enum
from typing import Optional


class MacroCycle(str, Enum):
    LIQUIDITY = "liquidity"
    INFLATION = "inflation"
    TECHNOLOGY = "technology"
    CREDIT = "credit"
    CURRENCY = "currency"
    GROWTH = "growth"


@dataclass
class HistoricalCase:
    case_id: str; date: str; title: str; cycle: MacroCycle
    macro_regime: dict = field(default_factory=dict)
    starting_conditions: dict = field(default_factory=dict)
    market_beliefs: str = ""; dominant_narrative: str = ""
    competing_narratives: list = field(default_factory=list)
    capital_flow: str = ""; asset_reaction: dict = field(default_factory=dict)
    expert_view: str = ""; actual_outcome: str = ""
    difficulty: str = "medium"; key_lesson: str = ""
    is_turning_point: bool = False
    causal_chain: list = field(default_factory=list)
    key_risks: list = field(default_factory=list)
    unknowns: list = field(default_factory=list)
    regime_description: str = ""


# ── Compact case tuples ─────────────────────────────────────────────
# Format: (id, date, title, cycle, (m,f,g,i,v,desc),
#   {cond_dict}, beliefs, narrative, [competing], flows, {assets},
#   expert, outcome, diff, lesson, is_tp,
#   [causal], [risks], [unknowns])

E="easing"; T="tightening"; N="neutral"; X="expansionary"; C="contractionary"
A="accelerating"; D="decelerating"; CO="contracting"; S="stable"
R="rising"; F="falling"; H="high"; L="low"; EX="extreme"; M="moderate"

LQ=MacroCycle.LIQUIDITY; INF=MacroCycle.INFLATION
TECH=MacroCycle.TECHNOLOGY; CRED=MacroCycle.CREDIT
FX=MacroCycle.CURRENCY; GR=MacroCycle.GROWTH

HARD="hard"; MED="medium"; EASY="easy"

def _make_regime(m,f,g,i,v,desc=""):
    return {"monetary":m,"fiscal":f,"growth":g,"inflation":i,"volatility":v,"description":desc or f"{m}_{f}_{g}_{i}"}

def _build_case(t) -> HistoricalCase:
    """Build HistoricalCase from compact tuple."""
    rid, date, title, cycle, r_tup, cond, b, nar, comp, flows, ast, exp, out, diff, lesson, tp = t[:16]
    cc = t[16] if len(t)>16 else []; kr = t[17] if len(t)>17 else []; uk = t[18] if len(t)>18 else []
    m,f,g,i,v = r_tup[:5]; rd = r_tup[5] if len(r_tup)>5 else ""
    return HistoricalCase(
        case_id=rid, date=date, title=title, cycle=cycle,
        macro_regime=_make_regime(m,f,g,i,v,rd),
        starting_conditions=cond, market_beliefs=b,
        dominant_narrative=nar, competing_narratives=comp,
        capital_flow=flows, asset_reaction=ast,
        expert_view=exp, actual_outcome=out,
        difficulty=diff, key_lesson=lesson, is_turning_point=tp,
        causal_chain=cc, key_risks=kr, unknowns=uk,
        regime_description=rd)


